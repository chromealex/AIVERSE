struct RocketContact {std::optional<aiverse::Fixed> distance; aiverse::Entity entity;};
inline RocketContact rocketWall(aiverse::World& world,const aiverse::game::Rules& rules,aiverse::Vec3 from,aiverse::Vec3 direction,aiverse::Fixed length,aiverse::Fixed radius){
 using namespace aiverse;using namespace game;
 RocketContact best;
 world.each<Unit,Transform>([&](Entity e,const Unit& u,const Transform& t){
  if(u.hp.raw<=0||u.type>=rules.types.size()||!rules.types[u.type].id.starts_with("city_interior_"))return;
  if(fxAbs(t.pos.x-from.x)>length+Fixed::fromInt(20)||fxAbs(t.pos.z-from.z)>length+Fixed::fromInt(20))return;
  for(const auto& box:rocketWalls){
   if(rules.types[u.type].id!=box.type)continue;
   Fixed enter{},leave=length;
   auto axis=[&](Fixed p,Fixed d,Fixed center,int width){
    auto half=Fixed::fromRatio(width,2000)+radius;
    if(!d.raw)return p>=center-half&&p<=center+half;
    auto a=(center-half-p)/d,b=(center+half-p)/d;if(a>b)std::swap(a,b);
    enter=fxMax(enter,a);leave=fxMin(leave,b);return enter<=leave;
   };
   if(axis(from.x,direction.x,t.pos.x+Fixed::fromRatio(box.x,1000),box.w)&&
      axis(from.z,direction.z,t.pos.z+Fixed::fromRatio(box.z,1000),box.d)&&
      (!best.distance||enter<*best.distance||(enter==*best.distance&&e.index<best.entity.index)))best={enter,e};
  }
 });
 return best;
}

