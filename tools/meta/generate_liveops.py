#!/usr/bin/env python3
"""Embed the authoritative JSON schema for GPU/network-free C++ validation."""
import argparse
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
data = json.loads((root/'tools/meta/liveops.schema.json').read_text())
content = '// Generated by tools/meta/generate_liveops.py; do not edit.\n#pragma once\nnamespace aiverse::meta::live {\ninline constexpr const char* kSchema = R"META(' + json.dumps(data, separators=(',', ':')) + ')META";\n}\n'
path = root/'engine/meta/LiveOpsSchema.h'
if a.check:
    if path.read_text() != content:
        p.error('generated schema differs')
else:
    path.write_text(content)
