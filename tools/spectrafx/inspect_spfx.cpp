// SpectraFX Stage 42 — offline SPFX V2 inspector with PRIVACY-FIRST reports.
// c++ -std=c++20 -O2 -I. tools/spectrafx/inspect_spfx.cpp -o inspect_spfx
// Never opens a graphics Device or writes raw checkpoint data to a report.
#include "engine/fx/SpectraDiagnosticReport.h"
#include "engine/fx/SpectraDiagnosticBundle.h"
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

namespace fs=std::filesystem;
namespace spectra=aiverse::spectra;

static void usage() {
    std::cerr<<"usage: inspect_spfx [--json] [--report <safe.json>] "
             <<"[--bundle <safe.zip>] "
             <<"[--include-coordinates] [--include-identifiers] "
             <<"<checkpoint.spfx>\n"
             <<"All output is redacted by DEFAULT; raw particle/VM data is never exported.\n";
}

int main(int argc,char** argv) {
    bool json=false;
    spectra::GpuDiagnosticReportPrivacy privacy{};
    std::string inputName,reportName,bundleName;
    for(int i=1;i<argc;++i) {
        const std::string a=argv[i];
        if(a=="--json" && !json)json=true;
        else if(a=="--include-coordinates" && !privacy.includeWorldBounds)
            privacy.includeWorldBounds=true; // explicit opt-in
        else if(a=="--include-identifiers" && !privacy.includeGpuIdentifiers)
            privacy.includeGpuIdentifiers=true; // explicit opt-in
        else if(a=="--report" && reportName.empty() && i+1<argc)
            reportName=argv[++i];
        else if(a=="--bundle" && bundleName.empty() && i+1<argc)
            bundleName=argv[++i];
        else if(inputName.empty() && a.rfind("--",0)!=0)
            inputName=a;
        else {usage();return 2;}
    }
    if(inputName.empty() ||
       (!reportName.empty() &&
        (reportName==inputName || reportName=="-" ||
         reportName.rfind("--",0)==0)) ||
       (!bundleName.empty() &&
        (bundleName==inputName || bundleName==reportName ||
         bundleName=="-" || bundleName.rfind("--",0)==0))) {
        usage();return 2;
    }

    std::error_code ec;
    const uintmax_t fileBytes=fs::file_size(inputName,ec);
    if(ec) {
        std::cerr<<"SPFX: cannot stat input: "<<ec.message()<<"\n";return 2;
    }
    if(fileBytes>spectra::kGpuCheckpointExportMaxBytes) {
        std::cerr<<"SPFX: file exceeds maximum bounded diagnostic payload\n";
        return 2;
    }
    std::ifstream input(inputName,std::ios::binary);
    if(!input) {std::cerr<<"SPFX: cannot open input\n";return 2;}
    std::vector<uint8_t> bytes(static_cast<size_t>(fileBytes));
    if(!bytes.empty())
        input.read(reinterpret_cast<char*>(bytes.data()),
                   static_cast<std::streamsize>(bytes.size()));
    if(!input && !bytes.empty()) {
        std::cerr<<"SPFX: input truncated while reading\n";return 2;
    }
    char extra=0;
    if(input.get(extra)) {
        std::cerr<<"SPFX: file grew during inspection\n";return 2;
    }
    const auto report=spectra::inspectGpuCheckpointDiagnostic(bytes);
    const std::string safe=spectra::gpuDiagnosticReportJson(report,privacy);
    if(!reportName.empty()) {
        // Explicit local destination ONLY, never auto-upload or embed raw
        // world positions/VM values unless the opt-in flags allow the bounds.
        // Never overwrite the original diagnostic binary by mistake.
        std::error_code pathsError;
        if(fs::equivalent(inputName,reportName,pathsError) &&
           !pathsError) {
            std::cerr<<"SPFX: report path must differ from input\n";return 2;
        }
        const fs::path output(reportName);
        const fs::path tmp=output.string()+".tmp";
        {
            std::ofstream stream(tmp,std::ios::binary|std::ios::trunc);
            if(!stream) {
                std::cerr<<"SPFX: cannot create redacted report\n";return 2;
            }
            stream.write(safe.data(),static_cast<std::streamsize>(safe.size()));
            stream.flush();
            if(!stream) {
                stream.close();
                fs::remove(tmp,ec);
                std::cerr<<"SPFX: failed to write redacted report\n";return 2;
            }
        }
        fs::rename(tmp,output,ec);
        if(ec) {
            fs::remove(tmp);
            std::cerr<<"SPFX: cannot publish redacted report: "<<ec.message()<<"\n";
            return 2;
        }
    }
    if(!bundleName.empty()) {
        // This intentionally ignores ALL sensitive --include-* flags:
        // safe bundle always stores redacted summaries and an empty
        // timeline when generated by the offline CLI.
        if(!report.structurallyValid()) {
            std::cerr<<"SPFX: invalid checkpoints cannot be bundled as valid diagnostics\n";
            return 1;
        }
        std::error_code check;
        if(fs::equivalent(inputName,bundleName,check) && !check) {
            std::cerr<<"SPFX: bundle cannot overwrite raw input\n";
            return 2;
        }
        if(!reportName.empty()) {
            check.clear();
            if(fs::equivalent(reportName,bundleName,check) && !check) {
                std::cerr<<"SPFX: bundle and JSON report must have distinct paths\n";
                return 2;
            }
        }
        std::vector<uint8_t> zip;
        const std::vector<spectra::GpuSafeTimelineFrame> noTimeline;
        if(!spectra::makeSafeGpuDiagnosticZip(report,noTimeline,zip)) {
            std::cerr<<"SPFX: bounded support-bundle preparation failed\n";
            return 2;
        }
        const fs::path target(bundleName);
        const fs::path tmp=target.string()+".tmp";
        {
            std::ofstream out(tmp,std::ios::binary|std::ios::trunc);
            if(!out) {
                std::cerr<<"SPFX: cannot create safe ZIP bundle\n";
                return 2;
            }
            out.write(reinterpret_cast<const char*>(zip.data()),
                      static_cast<std::streamsize>(zip.size()));
            out.flush();
            if(!out) {
                out.close();fs::remove(tmp,ec);
                std::cerr<<"SPFX: failed to write safe ZIP bundle\n";
                return 2;
            }
        }
        ec.clear();
        fs::rename(tmp,target,ec);
        if(ec) {
            fs::remove(tmp);
            std::cerr<<"SPFX: cannot publish safe ZIP bundle: "
                     <<ec.message()<<"\n";
            return 2;
        }
    }
    if(json)std::cout<<safe;
    else if(report.structurallyValid()) {
        std::cout<<"SPFX V2: valid payload length and CRC32\n"
                 <<"Physical slots "<<report.header.physicalSlots<<", live "
                 <<report.liveSlots<<", dead "<<report.deadSlots<<"\n"
                 <<"Nonfinite live "<<report.nonFiniteLiveSlots
                 <<", age anomalies "<<report.invalidAgeSlots
                 <<", lifespan mirror anomalies "<<report.invalidCpuLifetimeSlots
                 <<", life mismatches "<<report.mismatchedLifeSlots<<"\n";
        if(privacy.includeGpuIdentifiers)
            std::cout<<"GPU frame "<<report.header.gpuFrameSerial
                     <<", revision "<<report.header.capturedRevision<<"\n";
        if(privacy.includeWorldBounds && report.containsLivePositions)
            std::cout<<"World bounds ["<<report.minPosition[0]<<", "
                     <<report.minPosition[1]<<", "<<report.minPosition[2]
                     <<"] to ["<<report.maxPosition[0]<<", "
                     <<report.maxPosition[1]<<", "<<report.maxPosition[2]<<"]\n";
        if(report.hasSemanticWarnings())
            std::cout<<"WARNING: unusual particle values (not hardware-verified)\n";
        std::cout<<"Report redacts world bounds/identifiers unless explicitly enabled.\n";
    } else {
        std::cerr<<"SPFX inspection failed: "
                 <<spectra::gpuDiagnosticErrorString(report.error)<<"\n";
    }
    return report.structurallyValid()?0:1;
}
