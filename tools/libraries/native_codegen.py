#!/usr/bin/env python3
"""Generate a C++ native module, typed NativeState and Command codecs from a strict schema."""
import argparse
import json
import keyword
from gameplay import read_json
import re
import shutil
import tempfile
from pathlib import Path
IDENT = re.compile(r'[a-z][a-z0-9_]*\Z')
RESERVED = set('class struct union enum namespace template typename auto bool int long short char float double void return if else switch case default for while do break continue static const public private protected virtual override final new delete this operator friend using try catch throw sizeof alignas alignof concept requires co_await co_return co_yield nullptr true false signed unsigned volatile register extern mutable inline constexpr consteval constinit thread_local asm decltype explicit export noexcept reinterpret_cast static_cast const_cast dynamic_cast typeid wchar_t char8_t char16_t char32_t and or not xor bitand bitor compl and_eq or_eq xor_eq not_eq'.split())
def obj(v, keys):
    if not isinstance(v, dict) or set(v)-set(keys): raise ValueError('unknown fields or expected object')
def ident(v):
    if not isinstance(v,str) or not IDENT.fullmatch(v) or '__' in v or v in RESERVED or keyword.iskeyword(v): raise ValueError('invalid identifier: '+str(v))
    return v
def num(v,lo=-(2**63),hi=2**63-1):
    if type(v) is not int or not lo<=v<=hi: raise ValueError('integer out of range')
    return v
def fields(values):
    if not isinstance(values,list):raise ValueError('fields must be an array')
    names=set()
    for f in values:
        obj(f,('name','type','min','max','default'));name=ident(f['name'])
        if name in names or name in ('schema_version','initialize','load','store','valid','migrate','raw','out','version','next','value','cmd','player'):raise ValueError('duplicate/reserved field')
        names.add(name)
        if f.get('type','int64') not in ('int64','bool'):raise ValueError('type must be int64 or bool')
        low,high=(0,1) if f.get('type')=='bool' else (num(f['min']),num(f['max']))
        if low>high:raise ValueError('inverted field range')
        num(f['default'],low,high)
    return values
def bounds(f):return (0,1) if f.get('type')=='bool' else (f['min'],f['max'])
def literal(n):return '(-9223372036854775807LL - 1)' if n==-(2**63) else str(n)+'LL'
def check(f,expr):
    lo,hi=bounds(f);return f'({expr} >= {literal(lo)} && {expr} <= {literal(hi)})'
def validate(s):
    obj(s,('module','version','commandType','fields','commands','migrations'));ident(s['module']);num(s['version'],1,2**32-1);num(s['commandType'],32768,65535)

    if s['module'] in ('std','rts','main'):raise ValueError('reserved module name')
    if len(s['fields'])>128:raise ValueError('too many state fields')
    fields(s['fields']);ids=set();names=set()
    if not isinstance(s['commands'],list):raise ValueError('commands must be an array')
    for c in s['commands']:
        obj(c,('name','id','args'));ident(c['name']);
        if c['name'] in ('load','store','initialize','migrate','dispatch','encode'):raise ValueError('reserved command name')
        num(c['id'],1,2**31-1);fields(c['args'])
        if c['name'] in names or c['id'] in ids:raise ValueError('duplicate command')
        if len(c['args'])>32:raise ValueError('too many command arguments')
        names.add(c['name']);ids.add(c['id'])
    seen=set()
    for m in s.get('migrations',[]):
        obj(m,('from','to','rename','set','erase'));num(m['from'],1,s['version']-1);num(m['to'],m['from']+1,s['version'])
        if m['from'] in seen:raise ValueError('ambiguous migration')
        seen.add(m['from'])
        if not isinstance(m.get('rename',{}),dict) or not isinstance(m.get('set',{}),dict) or not isinstance(m.get('erase',[]),list):raise ValueError('invalid migration operations')
        for k,v in m.get('rename',{}).items():ident(k);ident(v)
        for k,v in m.get('set',{}).items():ident(k);num(v)
        for k in m.get('erase',[]):ident(k)
    return s
def generate(s):
    s=validate(s);ns=s['module'];version=s['version']
    header=['// Generated by native_codegen.py. Edit schema.json and regenerate into a new directory.','#pragma once','#include "modules/rts/RtsNative.h"','#include <optional>','#include <utility>',f'namespace {ns} {{',f'inline constexpr std::int64_t schemaVersion={version};','struct State {']
    for f in s['fields']:header.append(f'    {"bool" if f.get("type")=="bool" else "std::int64_t"} {f["name"]}={"true" if f.get("type")=="bool" and f["default"] else "false" if f.get("type")=="bool" else literal(f["default"])};')
    header+=['    bool valid() const { return '+(' && '.join(check(f,f['name']) for f in s['fields'] if f.get('type')!='bool') or 'true')+'; }','};','inline std::optional<State> load(const aiverse::game::NativeState& raw) {','    auto version=raw.values.find("schema_version"); if(version==raw.values.end()||version->second!=schemaVersion)return {};','    State out;']
    for f in s['fields']:
        n=f['name'];header += [f'    auto {n}=raw.values.find("{n}"); if({n}==raw.values.end()||!{check(f,n+"->second")})return {{}};',f'    out.{n}={n}->second'+('!=0;' if f.get('type')=='bool' else ';')]
    header+=['    return out;','}','inline bool store(aiverse::game::NativeState& raw,const State& value) {','    if(!value.valid())return false;', '    auto prior=raw.values.find("schema_version");if(!raw.values.empty()&&(prior==raw.values.end()||prior->second!=schemaVersion))return false; auto next=raw;', '    next.values["schema_version"]=schemaVersion;']
    for f in s['fields']:header.append(f'    next.values["{f["name"]}"]=value.{f["name"]};')
    header+=['    raw=std::move(next);return true;','}','inline bool initialize(aiverse::game::NativeState& raw){','    if(!raw.values.empty()||!raw.arrays.empty())return false;return store(raw,State{});','}','inline bool migrate(aiverse::game::NativeState& raw){','    auto next=raw;auto it=next.values.find("schema_version");if(it==next.values.end())return false;','    auto version=it->second;','    while(version<schemaVersion){','        switch(version){']
    for m in s.get('migrations',[]):
        header.append(f'        case {m["from"]}: {{')
        for old,new in m.get('rename',{}).items():header += ['            {',f'            auto found=next.values.find("{old}");if(found==next.values.end()||next.values.count("{new}"))return false;',f'            auto value=found->second;next.values.erase(found);next.values["{new}"]=value;', '            }']
        for key,value in m.get('set',{}).items():header.append(f'            next.values["{key}"]={literal(value)};')
        for key in m.get('erase',[]):header.append(f'            next.values.erase("{key}");')
        header += [f'            version={m["to"]};break;','        }']
    header+=['        default:return false;','        }','    }','    next.values["schema_version"]=version;if(!load(next))return false;raw=std::move(next);return true;','}','}']
    commands=['// Generated command codecs. Host must validate ownership/resources before applying.','#pragma once','#include "engine/sim/Command.h"','#include <optional>',f'namespace {ns} {{',f'inline constexpr std::uint16_t commandType={s["commandType"]};']
    for c in s['commands']:
        n=c['name'];commands.append(f'struct {n} {{')
        for f in c['args']:commands.append(f'    {"bool" if f.get("type")=="bool" else "std::int64_t"} {f["name"]}={literal(f["default"])};')
        commands+=['};',f'inline std::optional<{n}> decode_{n}(const aiverse::Command& cmd) {{',f'    if(cmd.type!=commandType||cmd.param!={c["id"]}||cmd.args.size()!={len(c["args"])}||cmd.player==0)return {{}};']
        for i,f in enumerate(c['args']):commands.append(f'    if(!{check(f,"cmd.args["+str(i)+"]")})return {{}};')
        commands += [f'    return {n}{{'+','.join(f'(cmd.args[{i}]!=0)' if f.get('type')=='bool' else f'cmd.args[{i}]' for i,f in enumerate(c['args']))+'};','}',f'inline std::optional<aiverse::Command> encode(std::uint8_t player,const {n}& value) {{','    if(player==0)return {};']
        if not c['args']:commands.append('    (void)value;')
        for f in c['args']:
            if f.get('type')!='bool':commands.append(f'    if(!{check(f,"value."+f["name"])})return {{}};')
        commands += [f'    aiverse::Command cmd;cmd.player=player;cmd.type=commandType;cmd.param={c["id"]};cmd.args={{'+','.join('value.'+f['name'] for f in c['args'])+'};return cmd;','}']
    commands+=['template<class Apply> bool dispatch(const aiverse::Command& cmd,Apply apply){','    switch(cmd.param){']
    for c in s['commands']:commands.append(f'    case {c["id"]}: {{auto value=decode_{c["name"]}(cmd);return value ? apply(*value) : false;}}')
    commands+=['    default:return false;','    }','}','}']
    source=f'''#include "State.h"
#include "Commands.h"
#include <stdexcept>
namespace {{
class Module final : public aiverse::game::NativeModule {{
public:
    void setup(aiverse::game::RtsModule&,aiverse::Simulation&,aiverse::game::NativeState& state,const aiverse::Json&)const override {{
        if(!{ns}::initialize(state))throw std::runtime_error("{ns}: invalid initial state");
    }}
    // Add game-specific command validation and effects here. Invalid commands must be ignored.
    // Use {ns}::dispatch(cmd, handler), load(state), then store(state, next).
}};
}}
std::unique_ptr<aiverse::game::NativeModule> create_{ns}(){{return std::make_unique<Module>();}}
'''
    smoke='#include "State.h"\n#include "Commands.h"\nint main(){aiverse::game::NativeState state;if(!'+ns+'::initialize(state)||!'+ns+'::load(state))return 1;\n'
    for c in s['commands']:smoke+='if(auto cmd='+ns+'::encode(1,'+ns+'::'+c['name']+'{});!cmd||!'+ns+'::decode_'+c['name']+'(*cmd))return 2;\n'
    smoke+='return 0;}\n'
    return {'Smoke.cpp':smoke,'State.h':'\n'.join(header)+'\n','Commands.h':'\n'.join(commands)+'\n','Module.cpp':source,'CMakeLists.txt':f'aiverse_native_module(ID {ns} VERSION {version} ENTRY create_{ns} SOURCES Module.cpp)\ntarget_link_libraries(aiverse_native_{ns} PRIVATE AIVERSE::gameplay_native)\n','schema.json':json.dumps(s,indent=2)+'\n','rules.fragment.json':json.dumps({'nativeModules':[{'id':ns,'version':version,'command':s['commandType'],'config':{}}]},indent=2)+'\n'}
def write(s,output):
    files=generate(s)
    if output.exists():raise ValueError('output exists; generate separately and review a diff')
    output.parent.mkdir(parents=True,exist_ok=True)
    stage=Path(tempfile.mkdtemp(prefix='.native-gen-',dir=str(output.parent)))
    try:
        for name,text in files.items():(stage/name).write_text(text)
        stage.rename(output)
    finally:
        if stage.exists():shutil.rmtree(stage)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--schema',required=True,type=Path);p.add_argument('--output',required=True,type=Path);a=p.parse_args()
    try:write(read_json(a.schema),a.output)
    except (ValueError,KeyError,TypeError) as e:p.error(str(e))
if __name__=='__main__':main()
