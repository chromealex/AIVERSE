#!/usr/bin/env python3
"""Generate C++ configuration, JSON Schema, and API settings reference from one spec."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]

def generate():
    spec=json.loads((ROOT/'libraries/spec/gameplay.json').read_text())
    code=['// Generated by tools/libraries/generate_gameplay.py. Edit libraries/spec/gameplay.json.', '#pragma once', '#include <charconv>', '#include <cstdint>', '#include <optional>', '#include <string>', '#include <vector>', 'namespace aiverse::lib::gameplay {']
    schema={'$schema':'https://json-schema.org/draft/2020-12/schema','title':'AIVERSE gameplay configuration','type':'object','additionalProperties':False,'required':['schemaVersion'],'properties':{'schemaVersion':{'const':spec['version']}}}
    doc=['# Настройки игровых подсистем','', 'Generated from `libraries/spec/gameplay.json`. Integer values are literal integers; no floating conversion.', '', '| Section | Field | Type | Default | Range |','|---|---|---|---|---|']
    constraints=[]
    for key,p in spec['packages'].items():
        code.append('struct '+p['type']+' {')
        fields={}
        for name,f in p['fields'].items():
            typ='bool' if f['type']=='boolean' else 'std::int64_t'
            value=str(f['default']).lower();code.append(f'    {typ} {name}={value};')
            fields[name]=f
            doc.append(f"| {key} | {name} | {f['type']} | {value} | {str(f.get('minimum',''))+'..'+str(f.get('maximum','')) if f['type']=='integer' else ''} |")
        code.append('};')
        schema['properties'][key]={'type':'object','additionalProperties':False,'properties':fields}
    code.append('struct GameplaySettings {')
    for key,p in spec['packages'].items():code.append(f"    {p['type']} {key};")
    code+=['};','struct SettingsResult { std::optional<GameplaySettings> value;std::vector<std::string> errors; };',
'''template<class Json> SettingsResult readGameplaySettings(const Json& root) {
    SettingsResult result; GameplaySettings settings;
    if(!root.isObject()){result.errors.push_back("configuration must be an object");return result;}
    auto number=[&](const Json& v,std::int64_t& out,std::int64_t low,std::int64_t high,const std::string& path){
        if(!v.isNumber()){result.errors.push_back(path+": expected integer");return;}
        const auto& text=v.numberLiteral();std::int64_t value=0;
        auto parsed=std::from_chars(text.data(),text.data()+text.size(),value);
        if(parsed.ec!=std::errc{}||parsed.ptr!=text.data()+text.size()||value<low||value>high)result.errors.push_back(path+": integer out of range");
        else out=value;
    };
    auto boolean=[&](const Json& v,bool& out,const std::string& path){
        if(v.type()!=Json::Type::Bool)result.errors.push_back(path+": expected boolean");else out=v.boolean();
    };
    std::int64_t version=0;number(root["schemaVersion"],version,1,1,"schemaVersion");''']
    allowed=['schemaVersion',*spec['packages']]
    code.append('    for(const auto& entry:root.members()) if('+ ' && '.join('entry.first!="'+k+'"' for k in allowed)+') result.errors.push_back(entry.first+": unknown section");')
    for key,p in spec['packages'].items():
        code.append(f'    if(root.has("{key}")) {{ const auto& section=root["{key}"];')
        code.append(f'        if(!section.isObject()) result.errors.push_back("{key}: expected object");')
        code.append('        else {')
        code.append('            for(const auto& entry:section.members()) if('+' && '.join('entry.first!="'+k+'"' for k in p['fields'])+f') result.errors.push_back("{key}."+entry.first+": unknown field");')
        for name,f in p['fields'].items():
            call=f'boolean(section["{name}"],settings.{key}.{name},"{key}.{name}")' if f['type']=='boolean' else f'number(section["{name}"],settings.{key}.{name},{f["minimum"]},{f["maximum"]},"{key}.{name}")'
            code.append(f'            if(section.has("{name}")) {call};')
        code.append('        }')
        for a,b in p.get('relations',[]):
            code.append(f'        if(settings.{key}.{a}>settings.{key}.{b})result.errors.push_back("{key}.{a}: must not exceed {b}");')
            constraints.append(f'Constraint: `{key}.{a} <= {key}.{b}` (checked by loader and CLI).')
        code.append('    }')
    code+=['    if(result.errors.empty()) result.value=settings;','    return result;','}','}']
    doc+=['','## Cross-field constraints','',*constraints]
    return {'libraries/include/aiverselib/gameplay/Configuration.h':'\n'.join(code)+'\n','libraries/spec/gameplay.schema.json':json.dumps(schema,indent=2)+'\n','docs/gameplay-settings.md':'\n'.join(doc)+'\n'}

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for file,text in generate().items():
        path=ROOT/file
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('stale generated file: '+file)
        else:path.write_text(text)
    print('Gameplay configuration generation: OK')
if __name__=='__main__':main()
