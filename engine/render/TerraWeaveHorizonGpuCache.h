struct HorizonGpuRegion {
    std::unique_ptr<render::Model> model;
    std::shared_ptr<const HorizonBake> bake;
    std::vector<render::ModelVertex> vertices; // optional patch reference
    std::vector<uint32_t> indices;             // optional patch reference
    int64_t originXcm=0, originZcm=0;
    size_t clusters=0, terrainQuads=0;
    size_t atlasBytes=0, vertexCount=0, triangleCount=0;
    size_t nearClipQuads=0, nearClipTriangles=0;
    bool nearClipFallback=false;
    size_t weldedNearVertices=0;
    int32_t maxNearWeldDeltaCm=0;
    size_t smoothedNearNormals=0;
    size_t matchedAuthoredNearNormals=0;
    size_t continuousNearNormalSamples=0;
    size_t localFallbackNearNormalSamples=0;
    bool nearNormalProvenanceAvailable=false;
    bool nearWeldSlopeFallback=false;
    size_t estimatedGpuBytes=0; // only texture+VB/IB, conservative mip allowance
    // Trailing field preserves existing positional aggregate users.
    // Moves with the GPU model through LRU and transition ownership.
    HorizonForestWindOverlay forestWind;
};

// Count retained CPU capacity (not the RHI GPU allocation). These vectors
// move together with a GPU model; callers must never strip one in isolation.
// The explicit 2 MiB per-model vertex capture limit is enforced elsewhere.
inline size_t horizonForestWindShadowCapacityBytes(
        const HorizonForestWindOverlay& shadow) {
    const size_t vertexBytes=shadow.vertices.capacity()*
                             sizeof(render::ModelVertex);
    const size_t centerBytes=shadow.centersCm.capacity()*
                             sizeof(std::pair<int64_t,int64_t>);
    const size_t compressedBytes=shadow.packedVertices.capacity();
    constexpr size_t maxBytes=std::numeric_limits<size_t>::max();
    if(vertexBytes>maxBytes-centerBytes ||
       compressedBytes>maxBytes-centerBytes-vertexBytes)
        return maxBytes;
    return vertexBytes+centerBytes+compressedBytes;
}

inline size_t estimateHorizonGpuResidencyBytes(
        size_t atlasBytes,size_t vertexCount,size_t triangleCount) {
    // RGBA8 atlas uses autogenerated mipmaps. 4/3 approximation rounds
    // upwards; small metadata and allocations receive a fixed 4 KiB charge.
    constexpr size_t kOverhead=4096;
    constexpr size_t kMax=std::numeric_limits<size_t>::max();
    if(atlasBytes>(kMax-kOverhead)/2 ||
       vertexCount>(kMax-kOverhead)/sizeof(render::ModelVertex) ||
       triangleCount>(kMax-kOverhead)/(3*sizeof(uint32_t)))
        return kMax;
    const size_t image=atlasBytes + (atlasBytes+2)/3;
    const size_t vertexBytes=vertexCount*sizeof(render::ModelVertex);
    const size_t indexBytes=triangleCount*3*sizeof(uint32_t);
    if(image>kMax-kOverhead || vertexBytes>kMax-kOverhead-image ||
       indexBytes>kMax-kOverhead-image-vertexBytes)
        return kMax;
    return kOverhead+image+vertexBytes+indexBytes;
}

class HorizonGpuRegionCache {
public:
    HorizonGpuRegionCache()=default;
    HorizonGpuRegionCache(const HorizonGpuRegionCache&)=delete;
    HorizonGpuRegionCache& operator=(const HorizonGpuRegionCache&)=delete;
    size_t size() const {return entries_.size();}
    size_t bytes() const {return occupiedBytes_;}
    size_t evictions() const {return evictions_;}
    size_t windShadowEvictions() const {return windShadowEvictions_;}
    size_t windShadowCompressions() const {return windShadowCompressions_;}
    size_t windShadowRestores() const {return windShadowRestores_;}
    size_t windShadowDecodeFailures() const {
        return windShadowDecodeFailures_;
    }
    size_t compressedWindShadowRegions() const {
        size_t count=0;
        for(const auto& [cell,entry]:entries_) {
            (void)cell;
            if(entry.region.forestWind.packedVertexCount)++count;
        }
        return count;
    }
    // One compression attempt per inactive cache entry, including entries
    // already resident when the native host enables packing at runtime.
    // An incompressible model is not repeatedly scanned every frame.
    void compactWindShadows() {
        for(auto& [cell,entry]:entries_) {
            (void)cell;
            if(entry.windCompressionAttempted)continue;
            if(compressHorizonForestWindOverlay(entry.region.forestWind))
                ++windShadowCompressions_;
            entry.windCompressionAttempted=true;
        }
    }
    size_t cachedWindShadowBytes() const {
        size_t sum=0;
        for(const auto& [cell,entry]:entries_) {
            (void)cell;
            const size_t bytes=horizonForestWindShadowCapacityBytes(
                entry.region.forestWind);
            if(bytes>std::numeric_limits<size_t>::max()-sum)
                return std::numeric_limits<size_t>::max();
            sum+=bytes;
        }
        return sum;
    }
    // A stored GPU VB may contain exact PHYSIS RGB rather than procedural
    // colours. It is unsafe to detach only its matching CPU shadow: the
    // next sparse patch would miscompare unknown GPU bytes. Evict the whole
    // oldest *shadow-bearing* cached model, never an active/fading model.
    // Revisit takes the existing streaming/asset path and recaptures both.
    void trimWindShadowBytes(gfx::Device& device,size_t budgetBytes) {
        while(cachedWindShadowBytes()>budgetBytes) {
            auto oldest=entries_.end();
            for(auto it=entries_.begin();it!=entries_.end();++it) {
                if(horizonForestWindShadowCapacityBytes(
                       it->second.region.forestWind)==0)continue;
                if(oldest==entries_.end() ||
                   it->second.stamp<oldest->second.stamp)
                    oldest=it;
            }
            if(oldest==entries_.end())break;
            release(device,oldest);
            ++windShadowEvictions_;
        }
    }

    // Only matching authored-landscape generations may be restored. Stale
    // generations are explicitly evicted via prune() on render owner thread.
    std::optional<HorizonGpuRegion> take(world::Cell cell,uint64_t revision) {
        auto it=entries_.find(cell);
        if(it==entries_.end()||it->second.revision!=revision)
            return std::nullopt;
        // Restore exact CPU bytes BEFORE reactivation. If allocation or
        // decoder validation fails the still-owned cached GPU entry remains
        // in the LRU; no mismatched partial GPU wind patch can run.
        if(restoreHorizonForestWindOverlay(it->second.region.forestWind))
            ++windShadowRestores_;
        HorizonGpuRegion result=std::move(it->second.region);
        occupiedBytes_-=result.estimatedGpuBytes;
        entries_.erase(it);
        return std::optional<HorizonGpuRegion>{std::move(result)};
    }
    // Render-thread device-aware activation: malformed packed snapshots
    // retire as complete GPU entries and fall through to normal streaming.
    // Ordinary memory-allocation errors still propagate to the host.
    std::optional<HorizonGpuRegion> take(
            gfx::Device& device,world::Cell cell,uint64_t revision) {
        try {
            return take(cell,revision);
        } catch(const std::logic_error&) {
            auto it=entries_.find(cell);
            if(it!=entries_.end() && it->second.revision==revision) {
                release(device,it);
                ++windShadowDecodeFailures_;
            }
            return std::nullopt;
        }
    }

    // A crossfading old region is an *additional* GPU resident, just
    // like a cache entry. Evict LRU entries first so transition memory
    // never silently exceeds the configured inactive-residency budget.
    // No GPU allocation takes place here; only explicit RHI retirements.
    bool reserveTransient(gfx::Device& device,size_t bytes,
                          size_t maxInactiveModels,size_t budgetBytes) {
        if(!bytes||bytes>budgetBytes||maxInactiveModels==0)
            return false;
        while(!entries_.empty() &&
              (entries_.size()>=maxInactiveModels ||
               bytes>budgetBytes-occupiedBytes_)) {
            auto oldest=entries_.begin();
            for(auto it=entries_.begin();it!=entries_.end();++it)
                if(it->second.stamp<oldest->second.stamp)
                    oldest=it;
            release(device,oldest);
        }
        return entries_.size()<maxInactiveModels &&
               bytes<=budgetBytes-occupiedBytes_;
    }

    void retain(gfx::Device& device,world::Cell cell,uint64_t revision,
                HorizonGpuRegion region,size_t limit,size_t budgetBytes,
                size_t windShadowBudgetBytes=16u*1024u*1024u,
                bool compressCachedShadows=false) {
        if(!region.model)return;
        if(!region.estimatedGpuBytes ||
           region.estimatedGpuBytes>budgetBytes || limit==0){
            render::releaseModel(device,*region.model);
            return;
        }
        // A duplicate key must not keep an obsolete model around.
        if(auto it=entries_.find(cell);it!=entries_.end()) {
            release(device,it);
        }
        while(!entries_.empty() &&
              (entries_.size()>=limit ||
               region.estimatedGpuBytes>budgetBytes-occupiedBytes_)){
            auto oldest=entries_.begin();
            for(auto it=entries_.begin();it!=entries_.end();++it)
                if(it->second.stamp<oldest->second.stamp)
                    oldest=it;
            release(device,oldest);
        }
        if(region.estimatedGpuBytes>budgetBytes-occupiedBytes_){
            render::releaseModel(device,*region.model);
            return;
        }
        const size_t cost=region.estimatedGpuBytes;
        entries_.emplace(cell,Entry{std::move(region),revision,++stamp_,false});
        occupiedBytes_+=cost;
        // Pack only after the record is safely owned by the LRU; this also
        // picks up older raw entries if compression was enabled mid-scene.
        if(compressCachedShadows)compactWindShadows();
        trimWindShadowBytes(device,windShadowBudgetBytes);
    }

    void prune(gfx::Device& device,uint64_t revision) {
        for(auto it=entries_.begin();it!=entries_.end();)
            if(it->second.revision!=revision) {
                auto stale=it++;
                release(device,stale);
            } else ++it;
    }

    void clear(gfx::Device& device) {
        for(auto& [cell,entry]:entries_) {
            (void)cell;
            if(entry.region.model)
                render::releaseModel(device,*entry.region.model);
        }
        entries_.clear();
        occupiedBytes_=0;
    }

private:
    struct Entry {
        HorizonGpuRegion region;
        uint64_t revision=0, stamp=0;
        bool windCompressionAttempted=false;
    };
    void release(gfx::Device& device,std::map<world::Cell,Entry>::iterator it) {
        if(it->second.region.model)
            render::releaseModel(device,*it->second.region.model);
        occupiedBytes_-=it->second.region.estimatedGpuBytes;
        ++evictions_;
        entries_.erase(it);
    }
    std::map<world::Cell,Entry> entries_;
    size_t occupiedBytes_=0;
    size_t evictions_=0; // LRU + invalidated terrain generations
    size_t windShadowEvictions_=0; // subset: CPU budget evicted whole GPU entry
    size_t windShadowCompressions_=0; // successful inactive lossless packs
    size_t windShadowRestores_=0; // GPU LRU reactivation with exact unpack
    size_t windShadowDecodeFailures_=0; // corrupt dormant GPU entries retired
    uint64_t stamp_=0;
};

